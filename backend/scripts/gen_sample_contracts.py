def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    n_pdf = n_docx = n_png = 0
    for c in CONTRACTS:
        out = OUT_DIR / c["file"]
        ext = out.suffix.lower()
        if ext == ".pdf":
            pages = make_pdf(c, out)
            n_pdf += 1
            print(f"  [PDF ] {c['file']}  {pages} 页")
        elif ext == ".docx":
            make_docx(c, out)
            n_docx += 1
            print(f"  [DOCX] {c['file']}  {len(c['clauses'])} 条")
        elif ext == ".png":
            w, h = make_png(c, out)
            n_png += 1
            print(f"  [PNG ] {c['file']}  {w}x{h}")
        else:
            raise ValueError(f"未知格式：{c['file']}")
    print(f"完成：PDF {n_pdf} / DOCX {n_docx} / PNG {n_png}，共 {n_pdf + n_docx + n_png} 份 → {OUT_DIR}")


if __name__ == "__main__":
    print("=" * 56)
    print("生成 20 份样例合同文件（8 PDF / 8 DOCX / 4 PNG）")
    print("=" * 56)
    main()
