# ===== Layout params (A4 595x842 pt, shared by PDF/PNG) =====
PAGE_W, PAGE_H = 595, 842
MARGIN = 60


def _pick_cjk_font() -> tuple[str, str | None]:
    """Prefer a real system font file (e.g. SimSun) when available.

    PyMuPDF's built-in china-s font has a broken ToUnicode mapping, so PDF text extraction
    drops characters at line ends (e.g. "256GB内存" is extracted as "25内存"), which makes
    the AI review misclassify it as high risk; a real font round-trips losslessly.
    """
    import os

    for name in ("simsun.ttc", "msyh.ttc", "simhei.ttf"):
        p = Path(os.environ.get("WINDIR", r"C:\\Windows")) / "Fonts" / name
        if p.exists():
            return "cjk", str(p)
    return "china-s", None  # Non-Windows fallback: built-in CJK (extraction may drop characters)


CJK_FONT, CJK_FONT_FILE = _pick_cjk_font()
BODY_SIZE, BODY_LINE = 10.5, 17.5
META_SIZE, META_LINE = 11, 19
TITLE_SIZE, TITLE_LINE = 17, 30


def disp_len(text: str) -> float:
    """Display width: full-width chars count as 1.0, half-width as 0.55 (unit: font size)."""
    w = 0.0
    for ch in text:
        w += 1.0 if ord(ch) > 0x2E80 else 0.55
    return w


def wrap_text(text: str, width_units: float) -> list[str]:
    """Wrap lines by display width."""
    lines, buf, buf_w = [], "", 0.0
    for ch in text:
        cw = 1.0 if ord(ch) > 0x2E80 else 0.55
        if buf_w + cw > width_units and buf:
            lines.append(buf)
            buf, buf_w = ch if ch != " " else "", cw if ch != " " else 0.0
        else:
            buf += ch
            buf_w += cw
    if buf:
        lines.append(buf)
    return lines


def _layout(blocks: list[tuple[str, str]]) -> fitz.Document:
    """[(text, style)] -> laid-out PDF document. style: title / meta / body / gap."""
    doc = fitz.open()
    page = doc.new_page(width=PAGE_W, height=PAGE_H)
    if CJK_FONT_FILE:
        page.insert_font(fontname=CJK_FONT, fontfile=CJK_FONT_FILE)
    y = MARGIN

    def new_page() -> None:
        nonlocal page, y
        page = doc.new_page(width=PAGE_W, height=PAGE_H)
        if CJK_FONT_FILE:
            page.insert_font(fontname=CJK_FONT, fontfile=CJK_FONT_FILE)
        y = MARGIN

    for text, style in blocks:
        if style == "gap":
            y += 10
            continue
        size, line_h = {
            "title": (TITLE_SIZE, TITLE_LINE),
            "meta": (META_SIZE, META_LINE),
            "body": (BODY_SIZE, BODY_LINE),
        }[style]
        width_units = (PAGE_W - 2 * MARGIN) / size
        for ln in wrap_text(text, width_units):
            if y + line_h > PAGE_H - MARGIN:
                new_page()
            if style == "title":
                x = (PAGE_W - disp_len(ln) * size) / 2
            elif style == "meta":
                x = PAGE_W - MARGIN - disp_len(ln) * size
            else:
                x = MARGIN
            page.insert_text((x, y + size), ln, fontname=CJK_FONT, fontsize=size)
            y += line_h
    return doc


def blocks_of(c: dict) -> list[tuple[str, str]]:
    blocks = [(c["title"], "title")]
    for m in c["meta"]:
        blocks.append((m, "meta"))
    blocks.append(("", "gap"))
    if c.get("preamble"):
        blocks.append((c["preamble"], "body"))
        blocks.append(("", "gap"))
    for cl in c["clauses"]:
        blocks.append((cl, "body"))
    return blocks


def make_pdf(c: dict, out: Path) -> int:
    doc = _layout(blocks_of(c))
    doc.save(str(out))
    n = doc.page_count
    doc.close()
    return n


def make_png(c: dict, out: Path) -> int:
    """Single-page layout -> 150dpi bitmap, simulating a scanned page."""
    doc = _layout(blocks_of(c))
    if doc.page_count != 1:
        doc.close()
        raise RuntimeError(f"{c['file']} 内容超过单页（{doc.page_count} 页），请精简 PNG 合同条款")
    pix = doc[0].get_pixmap(dpi=150)
    pix.save(str(out))
    doc.close()
    return pix.width, pix.height


def make_docx(c: dict, out: Path) -> int:
    d = DocxDocument()
    d.add_heading(c["title"], level=1)
    for m in c["meta"]:
        d.add_paragraph(m)
    if c.get("preamble"):
        d.add_paragraph(c["preamble"])
    for cl in c["clauses"]:
        d.add_paragraph(cl)
    d.save(str(out))
    return len(c["clauses"])


